#!/usr/bin/env python3
"""libm_check.py - compare the C RTL's math functions with glibc's (PORTING_LOG #27).

  libm_check.py gen [out.c]     write the probe (default probes/r_libm.c): every
        libm function PHP calls, over special values (signed zeros, infinities,
        NaN, subnormals, overflow edges) and ordinary ones; it prints one line
        per call, "RESULT <fn> <i> [<j>] <hex result>"
  libm_check.py compare <probe output> [ulps]
        compute the same calls with this host's glibc (ctypes) and list every
        result that differs: special-value errors (wrong NaN, infinity, sign of
        zero) and finite results more than <ulps> (default 1) apart

The VMS C RTL's rounding functions had already been found losing the sign of a
zero result (#26); the phpt math set also showed pow(0, -1) = -INF, fmod(x, 0)
= 0 and atan2(0, 0) = NAN.  This finds the full list in one pass.
"""
import ctypes, math, struct, sys

UNARY = ['sin', 'cos', 'tan', 'asin', 'acos', 'atan', 'sinh', 'cosh', 'tanh', 'asinh',
         'acosh', 'atanh', 'exp', 'expm1', 'log', 'log10', 'log2', 'log1p', 'sqrt', 'logb']
BINARY = ['atan2', 'pow', 'fmod', 'hypot', 'nextafter']

INF, NAN = float('inf'), float('nan')
X = [0.0, -0.0, 1.0, -1.0, 0.5, -0.5, 2.0, -2.0, 3.5, -3.5, 0.1, -0.1, 0.7, -0.7, 10.0, 23.45,
     -23.45, 100.0, 1e-10, -1e-10, 1e-300, 5e-324, -5e-324, 2.2250738585072014e-308, 1e300,
     -1e300, 709.78, 710.0, -745.0, -746.0, 0.9999999, 1.0000001, math.pi, math.pi / 2,
     math.e, 1e22, 2.0 ** 53, INF, -INF, NAN]
Y = [0.0, -0.0, 1.0, -1.0, 2.0, -2.0, 3.0, -3.0, 0.5, -0.5, 2.5, 1e-300, 1e300, 1024.0,
     -1075.0, INF, -INF, NAN]


def h(v):
    return struct.unpack('<Q', struct.pack('<d', v))[0]


def unh(s):
    return struct.unpack('<d', struct.pack('<Q', int(s, 16)))[0]


def lit(v):
    return '0x%016xULL' % h(v)


def gen(path):
    out = ['/* r_libm.c - generated by probes/libm_check.py gen: the C RTL\'s libm',
           '   results for the functions PHP calls, as hex, for libm_check.py compare. */',
           '#include <stdio.h>', '#include <string.h>', '#include <math.h>', '',
           'static double d(unsigned long long u) { double v; memcpy(&v, &u, 8); return v; }',
           'static unsigned long long u(double v) { unsigned long long r; memcpy(&r, &v, 8); return r; }',
           'static const unsigned long long X[] = {%s};' % ', '.join(lit(v) for v in X),
           'static const unsigned long long Y[] = {%s};' % ', '.join(lit(v) for v in Y),
           '#define NX %d' % len(X), '#define NY %d' % len(Y), '',
           'int main(void)', '{', '  int i, j;', '  volatile double a, b;']
    for f in UNARY:
        out.append('  for (i = 0; i < NX; i++) { a = d(X[i]); '
                   'printf("RESULT %s %%d %%016llx\\n", i, u(%s(a))); }' % (f, f))
    for f in BINARY:
        out.append('  for (i = 0; i < NX; i++) for (j = 0; j < NY; j++) { a = d(X[i]); b = d(Y[j]); '
                   'printf("RESULT %s %%d %%d %%016llx\\n", i, j, u(%s(a, b))); }' % (f, f))
    out += ['  return 0;', '}', '']
    open(path, 'w').write('\n'.join(out))


def ulps(a, b):
    ia, ib = h(a), h(b)
    ia = ia if ia < 1 << 63 else (1 << 63) - ia
    ib = ib if ib < 1 << 63 else (1 << 63) - ib
    return abs(ia - ib)


def compare(path, tol):
    m = ctypes.CDLL('libm.so.6')
    for f in UNARY:
        getattr(m, f).restype = ctypes.c_double
        getattr(m, f).argtypes = [ctypes.c_double]
    for f in BINARY:
        getattr(m, f).restype = ctypes.c_double
        getattr(m, f).argtypes = [ctypes.c_double, ctypes.c_double]
    bad = {}
    n = 0
    for line in open(path, encoding='latin-1'):
        p = line.split()
        if not p or p[0] != 'RESULT':
            continue
        f = p[1]
        if f in UNARY:
            args = (X[int(p[2])],)
        elif f in BINARY:
            args = (X[int(p[2])], Y[int(p[3])])
        else:
            continue
        n += 1
        got, want = unh(p[-1]), getattr(m, f)(*args)
        if math.isnan(want) and math.isnan(got):
            continue
        special = (math.isnan(want) or math.isnan(got) or math.isinf(want) or math.isinf(got)
                   or want == 0 or got == 0)
        if special and h(got) == h(want):
            continue
        if not special and ulps(got, want) <= tol:
            continue
        kind = 'special' if special else '%d ulp' % ulps(got, want)
        bad.setdefault(f, []).append('%s(%s) = %r, want %r [%s]' % (
            f, ', '.join(repr(a) for a in args), got, want, kind))
    print('libm_check: %d results, %d functions differ' % (n, len(bad)))
    for f in sorted(bad):
        print('== %s: %d' % (f, len(bad[f])))
        for b in bad[f]:
            print('   ' + b)


if __name__ == '__main__':
    if sys.argv[1] == 'gen':
        gen(sys.argv[2] if len(sys.argv) > 2 else 'probes/r_libm.c')
    else:
        compare(sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 1)
