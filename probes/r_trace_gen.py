#!/usr/bin/env python3
"""r_trace_gen: write r_trace_stubs.s, one counting stub per C RTL routine
named in r_trace_funcs.txt (the X-decc$ code symbols of PHP_CGI's map), and
r_trace_names.h, their names for r_trace.c. Linked in front of PHP_CGI's
objects, a stub takes the routine's name, counts the call and tail-jumps to
DECC$SHR's routine (found on the first call by r_trace_resolve). Nothing but
%r11 is touched on the way through: %rax carries the VMS argument
information. For PORTING_LOG #53: which calls follow the request count with
opcache on.

usage: r_trace_gen.py r_trace_funcs.txt outdir"""
import sys

names = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out = sys.argv[2]

s = ['# generated by r_trace_gen.py: counting stubs for %d C RTL routines' % len(names),
     '\t.text']
for i, n in enumerate(names):
    s += ['\t.globl\t"%s"' % n,
          '\t.p2align\t4',
          '"%s":' % n,
          '\tmovq\tr_trace_cnt@GOTPCREL(%rip), %r11',
          '\tincq\t%d(%%r11)' % (8 * i),
          '\tmovq\tr_trace_real@GOTPCREL(%rip), %r11',
          '\tmovq\t%d(%%r11), %%r11' % (8 * i),
          '\ttestq\t%r11, %r11',
          '\tjz\t.Lslow%d' % i,
          '\tjmpq\t*%r11',
          '.Lslow%d:' % i,
          '\tmovl\t$%d, %%r11d' % i,
          '\tjmp\tr_trace_slow']
# first call: save the argument registers (and %rax), resolve, restore, jump
s += ['\t.p2align\t4',
      'r_trace_slow:',
      '\tpushq\t%rbp',
      '\tmovq\t%rsp, %rbp']
regs = ['rax', 'rdi', 'rsi', 'rdx', 'rcx', 'r8', 'r9', 'r11']
s += ['\tpushq\t%%%s' % r for r in regs]
s += ['\tsubq\t$128, %rsp']
s += ['\tmovdqu\t%%xmm%d, %d(%%rsp)' % (k, 16 * k) for k in range(8)]
s += ['\tmovq\t%r11, %rdi',
      '\tmovl\t$256, %eax',
      '\tcallq\tr_trace_resolve',
      '\tmovq\t%rax, %r11']
s += ['\tmovdqu\t%d(%%rsp), %%xmm%d' % (16 * k, k) for k in range(8)]
s += ['\taddq\t$128, %rsp',
      '\tpopq\t%r10']
s += ['\tpopq\t%%%s' % r for r in reversed(regs[:-1])]
s += ['\tpopq\t%rbp',
      '\tjmpq\t*%r11', '']
open(out + '/r_trace_stubs.s', 'w').write('\n'.join(s))

h = ['/* generated by r_trace_gen.py */',
     '#define R_TRACE_N %d' % len(names),
     'static const char *const r_trace_names[R_TRACE_N] = {']
h += ['  "%s",' % n for n in names]
h += ['};', '']
open(out + '/r_trace_names.h', 'w').write('\n'.join(h))
